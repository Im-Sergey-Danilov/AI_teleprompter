#!/usr/bin/env bash
# Generates server/.env: a random API token, the GPU's compute capability,
# and a bind address. Safe to re-run - an existing .env is left alone.
set -euo pipefail
cd "$(dirname "$0")"

if [[ -f .env ]]; then
    echo ".env already exists, leaving it as is:"
    grep -vE '^API_TOKEN=' .env | sed 's/^/  /'
    echo "  API_TOKEN=<hidden>"
    exit 0
fi

# Compute capability -> nvcc arch (8.9 -> 89). Falls back to a broad set.
ARCH=$(nvidia-smi --query-gpu=compute_cap --format=csv,noheader 2>/dev/null \
       | head -1 | tr -d '.' | tr -d '[:space:]')
[[ -z "$ARCH" ]] && ARCH="75;80;86;89"

TOKEN=$(head -c 32 /dev/urandom | od -An -tx1 | tr -d ' \n')

# Prefer a VPN/LAN address over 0.0.0.0 so this is not published to the world.
BIND=$(ip -4 -o addr show scope global 2>/dev/null \
       | awk '{print $4}' | cut -d/ -f1 \
       | grep -vE '^(172\.1[6-9]\.|172\.2[0-9]\.|172\.3[01]\.)' \
       | head -1)
[[ -z "$BIND" ]] && BIND=127.0.0.1

cat > .env <<ENVEOF
# Generated by setup.sh - keep API_TOKEN secret.
API_TOKEN=$TOKEN

# Host interface the endpoint is published on. 127.0.0.1 = local only.
# Use a LAN or VPN address to reach it from another machine; 0.0.0.0 exposes
# it on every interface, including any public one.
WHISPER_BIND=$BIND
WHISPER_PORT=8910

WHISPER_MODEL=ggml-large-v3-turbo.bin
WHISPER_THREADS=4

# Language for requests that do not specify one. "auto" detects per utterance.
WHISPER_LANG=ru
WHISPER_TAG=v1.7.4
CUDA_ARCH=$ARCH
ENVEOF

chmod 600 .env
echo "Wrote .env"
echo "  endpoint  http://$BIND:8910/v1/audio/transcriptions"
echo "  api key   $TOKEN"
echo "  cuda arch $ARCH"
echo
echo "Next: ./get-model.sh large-v3-turbo && docker compose up -d --build"
